#!/bin/bash

# Скрипт для запуска тестов аутентификации с использованием Docker для тестовой базы данных

# Останавливаем контейнер с тестовой базой данных, если он уже запущен
docker-compose stop postgres-test

# Запускаем контейнер с тестовой базой данных
echo "Запуск тестовой базы данных..."
docker-compose up -d postgres-test

# Ждем, пока база данных запустится
echo "Ожидание запуска базы данных..."
sleep 5

# Установка переменной окружения для тестовой базы данных
export DATABASE_URL_TEST=postgresql://postgres:postgres@localhost:5434/happyness_test

# Применение миграций к тестовой БД
echo "Применение миграций к тестовой базе данных..."
npx prisma migrate deploy

# Запуск модульных тестов
echo "Запуск модульных тестов аутентификации..."
npm run test:auth

# Запуск интеграционных тестов
echo "Запуск интеграционных тестов аутентификации..."
npm run test:auth:integration

# Останавливаем контейнер с тестовой базой данных
echo "Остановка тестовой базы данных..."
docker-compose stop postgres-test

echo "Тесты аутентификации завершены!" 